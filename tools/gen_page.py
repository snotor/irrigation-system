#!/usr/bin/env python3
"""Turn a portal page into a header with a gzipped PROGMEM array (same minifier as gen_portal.py).

Controller UI:   python tools/gen_page.py portal/app.html include/AppPage.h APP
Setup page:      python tools/gen_page.py portal/index.html include/PortalPage.h PORTAL   (same as gen_portal.py)
Arguments:       <input.html> <output.h> <PREFIX>; the header defines PREFIX_GZ and PREFIX_GZ_LEN

The minifier is deliberately conservative (comments and indentation only), because
gzip removes the rest. Do not use multi-line template literals or full-line
"//" text inside strings in the page's script.
"""
import gzip
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "portal" / "app.html"
dst = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else root / "include" / "AppPage.h"
prefix = sys.argv[3] if len(sys.argv) > 3 else "APP"

html = src.read_text(encoding="utf-8")

html = re.sub(r"<!--.*?-->", "", html, flags=re.S)            # HTML comments
html = re.sub(r"/\*.*?\*/", "", html, flags=re.S)            # CSS comments (the page has no "/*" elsewhere)

lines = []
for line in html.splitlines():
    line = line.strip()
    if not line or line.startswith("//"):                    # blank lines, full-line JS comments
        continue
    lines.append(line)
data = "\n".join(lines).encode("utf-8")

gz = gzip.compress(data, compresslevel=9, mtime=0)           # mtime=0: same bytes every run

rows = []
for i in range(0, len(gz), 16):
    rows.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 16]))

out = (
    "// Generated by tools/gen_page.py from portal/%s. Do not edit by hand.\n"
    "#pragma once\n"
    "#include <Arduino.h>\n\n"
    "// %d bytes of HTML, %d bytes gzipped\n"
    "constexpr size_t %s_GZ_LEN = %d;\n"
    "static const uint8_t %s_GZ[] PROGMEM = {\n%s\n};\n"
) % (src.name, len(data), len(gz), prefix, len(gz), prefix, ",\n".join(rows))

dst.write_text(out, encoding="utf-8")
print("%s: %d B -> %d B gzipped -> %s" % (src.name, len(data), len(gz), dst))
