#!/usr/bin/env python3
"""Build the two web pages the firmware serves, as gzipped PROGMEM headers.

  portal/app-demo.html  --strip the offline demo-->  portal/app.html  --gzip-->  include/AppPage.h
  portal/index.html                                                   --gzip-->  include/PortalPage.h

app-demo.html is the UI with a fake controller (mock) and a "Demo" panel, so it runs on a laptop
without an ESP. The firmware page must not contain them, or the phone would talk to the mock.

Runs before every PlatformIO build (extra_scripts = pre:tools/build_pages.py) and also by hand:
    python tools/build_pages.py
The minifier is deliberately conservative (comments and indentation only); gzip removes the rest.
"""
import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent if "__file__" in globals() else pathlib.Path.cwd()
PORTAL = ROOT / "portal"
INCLUDE = ROOT / "include"


def strip_demo(html: str) -> str:
    """Remove the mock controller and the demo panel from app-demo.html."""
    rules = [
        # the fake controller: <script> // ===== OFFLINE DEMO ... </script>
        ("mock script", r"<script>\s*// ===== OFFLINE DEMO.*?</script>\s*"),
        # the demo panel's style block
        ("demo style", r"<style>\s*#dm\{.*?</style>\s*"),
        # the floating "Demo" button
        ("demo button", r'<button id="dm"[^>]*>.*?</button>\s*'),
        # the demo panel (its own lines end with "</div>"; the panel closes on a line of its own)
        ("demo panel", r'<div id="dp".*?\n</div>\n'),
        # the panel's script, which reads window.__MOCK
        ("demo controls script", r"<script>\s*\(function\(\)\{\s*var M=window\.__MOCK.*?</script>\s*"),
    ]
    for name, rx in rules:
        html, n = re.subn(rx, "", html, count=1, flags=re.S)
        if n != 1:
            sys.exit("build_pages: could not find the %s in app-demo.html; update tools/build_pages.py" % name)
    if "__MOCK" in html or "OFFLINE DEMO" in html:
        sys.exit("build_pages: demo code is still in the page")
    return html.replace("<title>Irrigation (demo)</title>", "<title>Irrigation</title>")


def minify(html: str) -> bytes:
    html = re.sub(r"<!--.*?-->", "", html, flags=re.S)        # HTML comments
    html = re.sub(r"/\*.*?\*/", "", html, flags=re.S)         # CSS comments (the pages have no "/*" elsewhere)
    lines = []
    for line in html.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):                # blank lines, full-line JS comments
            continue
        lines.append(line)
    return "\n".join(lines).encode("utf-8")


def write_header(data: bytes, src_name: str, dst: pathlib.Path, prefix: str) -> None:
    gz = gzip.compress(data, compresslevel=9, mtime=0)       # mtime=0: same bytes every run
    rows = ["  " + ",".join("0x%02x" % b for b in gz[i:i + 16]) for i in range(0, len(gz), 16)]
    out = (
        "// Generated by tools/build_pages.py from portal/%s. Do not edit by hand.\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        "// %d bytes of HTML, %d bytes gzipped\n"
        "constexpr size_t %s_GZ_LEN = %d;\n"
        "static const uint8_t %s_GZ[] PROGMEM = {\n%s\n};\n"
    ) % (src_name, len(data), len(gz), prefix, len(gz), prefix, ",\n".join(rows))
    if dst.exists() and dst.read_text(encoding="utf-8") == out:
        return                                                # unchanged: no rebuild
    dst.write_text(out, encoding="utf-8")
    print("build_pages: %s -> %s (%d B, %d B gzipped)" % (src_name, dst.name, len(data), len(gz)))


def main() -> None:
    INCLUDE.mkdir(exist_ok=True)
    demo = PORTAL / "app-demo.html"
    app = PORTAL / "app.html"
    if demo.exists():
        app.write_text(strip_demo(demo.read_text(encoding="utf-8")), encoding="utf-8")
    if not app.exists():
        sys.exit("build_pages: portal/app-demo.html (or portal/app.html) is missing")
    write_header(minify(app.read_text(encoding="utf-8")), app.name, INCLUDE / "AppPage.h", "APP")
    write_header(minify((PORTAL / "index.html").read_text(encoding="utf-8")), "index.html", INCLUDE / "PortalPage.h", "PORTAL")


try:                       # inside PlatformIO (SCons), Import() exists
    Import("env")          # noqa: F821
    IN_PIO = True
except NameError:
    IN_PIO = False

if IN_PIO:
    ROOT = pathlib.Path(env["PROJECT_DIR"])   # noqa: F821
    PORTAL, INCLUDE = ROOT / "portal", ROOT / "include"
    main()
elif __name__ == "__main__":
    main()
